function model = generated_build_thermal_stress_rectangle()
import com.comsol.model.*
import com.comsol.model.util.*
model = ModelUtil.create('Model');
model.param.set('L', '0.1[m]', 'L');
model.param.set('W', '0.02[m]', 'W');
model.param.set('E_mod', '210000000000[Pa]', 'E_mod');
model.param.set('nu_mat', '0.3[1]', 'nu_mat');
model.param.set('rho_mat', '7850[kg/m^3]', 'rho_mat');
model.param.set('k_mat', '45[W/(m*K)]', 'k_mat');
model.param.set('Cp_mat', '460[J/(kg*K)]', 'Cp_mat');
model.param.set('alpha_mat', '1.2e-05[1/K]', 'alpha_mat');
model.param.set('T_hot', '373.15[K]', 'T_hot');
model.param.set('T_cold', '293.15[K]', 'T_cold');
model.param.set('hmax', '0.002[m]', 'hmax');
model.component.create('comp1', true);
model.component('comp1').geom.create('geom1', 2);
model.component('comp1').geom('geom1').create('r1', 'Rectangle');
model.component('comp1').geom('geom1').feature('r1').set('size', {'L' 'W'});
model.component('comp1').geom('geom1').run;
model.component('comp1').material.create('mat1', 'Common');
model.component('comp1').material('mat1').propertyGroup('def').set('density', 'rho_mat');
model.component('comp1').material('mat1').propertyGroup('def').set('thermalconductivity', 'k_mat');
model.component('comp1').material('mat1').propertyGroup('def').set('heatcapacity', 'Cp_mat');
model.component('comp1').material('mat1').propertyGroup('def').set('youngsmodulus', 'E_mod');
model.component('comp1').material('mat1').propertyGroup('def').set('poissonsratio', 'nu_mat');
model.component('comp1').material('mat1').propertyGroup('def').set('thermalexpansioncoefficient', 'alpha_mat');
model.component('comp1').physics.create('ht', 'HeatTransfer', 'geom1');
model.component('comp1').physics('ht').selection.all;
model.component('comp1').physics('ht').create('temp1', 'TemperatureBoundary', 1);
model.component('comp1').physics('ht').feature('temp1').selection.set([1]);
model.component('comp1').physics('ht').feature('temp1').set('T0', 'T_hot');
model.component('comp1').physics('ht').create('temp2', 'TemperatureBoundary', 1);
model.component('comp1').physics('ht').feature('temp2').selection.set([3]);
model.component('comp1').physics('ht').feature('temp2').set('T0', 'T_cold');
model.component('comp1').physics.create('solid', 'SolidMechanics', 'geom1');
model.component('comp1').physics('solid').selection.all;
model.component('comp1').physics('solid').create('fix1', 'Fixed', 1);
model.component('comp1').physics('solid').feature('fix1').selection.set([1]);
model.component('comp1').multiphysics.create('te1', 'ThermalExpansion', 2);
model.component('comp1').multiphysics('te1').selection.all;
model.component('comp1').mesh.create('mesh1');
model.component('comp1').mesh('mesh1').create('size1', 'Size');
model.component('comp1').mesh('mesh1').feature('size1').set('custom', true);
model.component('comp1').mesh('mesh1').feature('size1').set('hmax', 'hmax');
model.component('comp1').mesh('mesh1').create('ftri1', 'FreeTri');
model.component('comp1').mesh('mesh1').run;
model.component('comp1').cpl.create('maxop1', 'Maximum');
model.component('comp1').cpl('maxop1').selection.all;
model.study.create('std1');
model.study('std1').create('stat', 'Stationary');
model.study('std1').feature('stat').activate('ht', true);
model.study('std1').feature('stat').activate('solid', true);
model.study('std1').createAutoSequences('all');
model.study('std1').run;
model.result.numerical.create('T_max', 'EvalGlobal'); model.result.numerical('T_max').set('expr', 'maxop1(T)');
model.result.numerical.create('u_max', 'EvalGlobal'); model.result.numerical('u_max').set('expr', 'maxop1(solid.disp)');
model.result.numerical.create('mises_max', 'EvalGlobal'); model.result.numerical('mises_max').set('expr', 'maxop1(solid.mises)');
end
